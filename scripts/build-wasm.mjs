/**
 * Compiles the Rust core to WebAssembly and embeds the binary as a base64
 * string module (src/generated/darts-wasm.ts), so both the CJS and ESM builds
 * carry it without resolving a file path at runtime.
 */

import { execFileSync } from 'node:child_process';
import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const target = 'wasm32-unknown-unknown';

execFileSync('cargo', ['build', '--release', '--locked', '-p', 'darts-core', '--target', target], {
  cwd: root,
  stdio: 'inherit',
});

const wasmPath = path.join(root, 'target', target, 'release', 'darts_core.wasm');
const wasm = fs.readFileSync(wasmPath);
const outDir = path.join(root, 'src', 'generated');
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(
  path.join(outDir, 'darts-wasm.ts'),
  `// Generated by scripts/build-wasm.mjs. Do not edit.\nexport const DARTS_WASM_BASE64: string =\n  '${wasm.toString('base64')}';\n`
);
console.log(`Embedded ${wasm.length} bytes of WebAssembly into src/generated/darts-wasm.ts`);
